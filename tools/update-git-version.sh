#!/usr/bin/env bash
# Writes the current git short hash to src/departure-board/git-version.h so the
# firmware can report it in telemetry. Run automatically by the git hooks from
# tools/install-git-hooks.sh, or by hand right before flashing.
set -euo pipefail

repo_root="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
hash="$(git -C "$repo_root" rev-parse --short HEAD)"

# Flag uncommitted firmware changes so a flashed build can't be mistaken for HEAD
if ! git -C "$repo_root" diff --quiet HEAD -- src/departure-board; then
  hash="${hash}-dirty"
fi

out="$repo_root/src/departure-board/git-version.h"
new="// Generated by tools/update-git-version.sh, do not edit or commit
#define FW_GIT_HASH \"$hash\""

# Only rewrite when it changes, so the IDE doesn't see a modified file for nothing
if [ ! -f "$out" ] || [ "$(cat "$out")" != "$new" ]; then
  printf '%s\n' "$new" > "$out"
fi

echo "FW_GIT_HASH = $hash"
